# Memasukkan koefisien persamaan linear
A = [
    [2.0, 1.0, 1.0, 10.0],
    [1.0, 2.0, 1.0, 11.0],
    [1.0, 1.0, 2.0, 12.0]
]

# Menampilkan matriks awal
print("Matriks Awal:")
for baris in A:
  print(baris)

# Melakukan proses eliminasi Gauss
n = 3

for i in range(n):
    # Menentukan elemen pivot
    pivot = A[i][i]

    # Membagi baris dengan nilai pivot
    for j in range(i, n + 1):
        A[i][j] = A[i][j] / pivot

    # Menghilangkan elemen di bawah pivot
    for k in range(i + 1, n):
        faktor = A[k][i]

        for j in range(i, n + 1):
            A[k][j] = A[k][j] - faktor * A[i][j]

# Menampilkan hasil eliminasi
print("Matriks setelah eliminasi Gauss:")
for baris in A:
    print(baris)

# Menghitung nilai variabel menggunakan substitusi balik

# Menghitung nilai z
z = A[2][3] / A[2][2]

# Menghitung nilai y
y = (A[1][3] - A[1][2] * z) / A[1][1]

# Menghitung nilai x
x = (A[0][3] - A[0][1] * y - A[0][2] * z) / A[0][0]

# Menampilkan hasil perhitungan
print("Hasil Penyelesaian SPL:")
print("Nilai x =", x)
print("Nilai y =", y)
print("Nilai z =", z)

# Menampilkan kesimpulan hasil penyelesaian SPL

print("KESIMPULAN")
print("Program berhasil menyelesaikan SPL 3 variabel.")
print("Metode yang digunakan adalah Eliminasi Gauss.")
print("Hasil penyelesaian:")
print("x =", x)
print("y =", y)
print("z =", z)

# Memeriksa hasil ke persamaan awal
print("\nPemeriksaan:")
print("Persamaan 1:", 2*x + y + z)
print("Persamaan 2:", x + 2*y + z)
print("Persamaan 3:", x + y + 2*z)